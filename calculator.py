# Простой калькулятор
def add(x, y):  # Функция сложения двух чисел
    return x + y  # Возвращаем сумму

def subtract(x, y):  # Функция вычитания второго числа из первого
    return x - y  # Возвращаем разность

def multiply(x, y):  # Функция умножения двух чисел
    return x * y  # Возвращаем произведение

def divide(x, y):  # Функция деления первого числа на второе
    if y != 0:  # Проверяем, чтобы делитель не был нулём
        return x / y  # Возвращаем результат деления
    else:  # Если делитель равен нулю
        return "Ошибка: деление на ноль"  # Возвращаем сообщение об ошибке

def calculator():  # Основная функция калькулятора
    print("Выберите операцию:")  # Приглашение к выбору операции
    print("1. Сложение")  # Вариант 1
    print("2. Вычитание")  # Вариант 2
    print("3. Умножение")  # Вариант 3
    print("4. Деление")  # Вариант 4
    while True:  # Бесконечный цикл для повторных вычислений
        choice = input("Введите номер операции (1/2/3/4) или 'q' для выхода: ")  # Запрос выбора у пользователя
        if choice == 'q':  # Если пользователь хочет выйти
            print("Выход из калькулятора.")  # Сообщение о выходе
            break  # Прерываем цикл
        if choice in ('1', '2', '3', '4'):  # Проверяем, что выбор корректен
            try:  # Попытка преобразовать ввод в числа
                num1 = float(input("Введите первое число: "))  # Ввод первого числа
                num2 = float(input("Введите второе число: "))  # Ввод второго числа
            except ValueError:  # Если ввод не число
                print("Ошибка ввода. Пожалуйста, введите числа.")  # Сообщение об ошибке
                continue  # Переходим к следующей итерации цикла
            if choice == '1':  # Если выбрано сложение
                print(f"Результат: {add(num1, num2)}")  # Выводим результат
            elif choice == '2':  # Если выбрано вычитание
                print(f"Результат: {subtract(num1, num2)}")  # Выводим результат
            elif choice == '3':  # Если выбрано умножение
                print(f"Результат: {multiply(num1, num2)}")  # Выводим результат
            elif choice == '4':  # Если выбрано деление
                print(f"Результат: {divide(num1, num2)}")  # Выводим результат
        else:  # Если выбор некорректен
            print("Неверный ввод. Пожалуйста, выберите операцию из списка.")  # Сообщение об ошибке

if __name__ == "__main__":  # Точка входа в программу
    calculator()  # Запускаем калькулятор